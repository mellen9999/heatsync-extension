/**
 * The page world's slice of the emoji dataset.
 *
 * Twitch is the one site where emoji-data runs in TWO worlds: the isolated
 * world (pickers, send-time :name: conversion) reads the full dataset, and the
 * page world's autocomplete-hook.js reads only [name, emoji]. Giving it the
 * full file meant parsing the whole 118KB a second time per page, `category`
 * and all. This cuts the file the page world loads down to the two fields it
 * reads, generated from the one source (chrome/emoji-data.js) so the two can
 * never disagree.
 */
import { runInNewContext } from 'node:vm'

/** [name, emoji] for every row of the dataset, in order. Throws on anything off. */
export function emojiPairs(dataSrc) {
  const rows = runInNewContext(`${dataSrc}\n;EMOJI_DATA`)
  if (!Array.isArray(rows) || rows.length < 1000) {
    throw new Error(`emoji-data.js: expected the full dataset, got ${rows?.length}`)
  }
  return rows.map((r, i) => {
    if (typeof r?.name !== 'string' || !r.name || typeof r?.emoji !== 'string' || !r.emoji) {
      throw new Error(`emoji-data.js: row ${i} has no name or emoji`)
    }
    return [r.name, r.emoji]
  })
}

/** The file the page world loads: `var EMOJI_PAIRS = [[name, emoji], ...]`. */
export function emojiPairsSource(dataSrc) {
  const lines = emojiPairs(dataSrc).map(([n, e]) => `  [${JSON.stringify(n)}, ${JSON.stringify(e)}],`)
  return (
    '// Generated by build.js from emoji-data.js. Do not edit.\n' +
    '// [name, emoji] pairs: all the page-world autocomplete reads (the full dataset stays in the isolated world).\n' +
    `var EMOJI_PAIRS = [\n${lines.join('\n')}\n]\n`
  )
}
